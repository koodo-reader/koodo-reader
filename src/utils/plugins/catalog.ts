const definitionsByKey = new Map(
  builtinPluginCatalog.map((definition) => [definition.key, definition])
);

export const getBuiltinPluginCatalog = () => builtinPluginCatalog;

export const getBuiltinPluginDefinition = (key: string) =>
  definitionsByKey.get(key);

export const isBuiltinPluginKey = (key: string) => definitionsByKey.has(key);

export const isBuiltinPluginType = (key: string, type: BuiltinPluginType) =>
  definitionsByKey.get(key)?.type === type;

export const getBuiltinPluginMarket = (
  language: string
): BuiltinPluginMarketItem[] => {
  const useChinese = language.startsWith("zh");
  return builtinPluginCatalog
    .filter(
      (definition) => useChinese || !chineseOnlyPluginKeys.has(definition.key)
    )
    .map((definition) => ({
      name: useChinese ? definition.name.zhCN : definition.name.en,
      feature: useChinese ? definition.feature.zhCN : definition.feature.en,
      configuration: useChinese
        ? definition.configuration.zhCN
        : definition.configuration.en,
      websiteName: definition.websiteName,
      websiteUrl: definition.websiteUrl,
      plugin: {
        identifier: definition.key,
        type: definition.type,
        displayName: definition.displayName,
        icon: definition.icon,
        version: definition.version,
        autoValue: definition.autoValue,
        config: structuredClone(definition.defaultConfig),
        langList: structuredClone(definition.langList),
        voiceList: structuredClone(definition.voiceList),
      },
    }));
};
